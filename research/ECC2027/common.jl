# Helpers shared by the experiments: results folder, numbers, tables, environment.
#
# Environment variables:
#   SAMPLES=n         timed rounds, median reported (default 3)
#   FIGURES=0         skip the figures and animations
#   RESULTS_DIR=path  output folder (default results/, /results on CodeOcean)

import Dates
import InteractiveUtils
import Dionysos
import MathOptInterface
import StaticArrays

const RESULTS = get(ENV, "RESULTS_DIR", joinpath(@__DIR__, "results"))
mkpath(RESULTS)

const SAMPLES = parse(Int, get(ENV, "SAMPLES", "3"))
const FIGURES = get(ENV, "FIGURES", "1") == "1"

# Runs f() `samples` times, with a GC before each, and returns the last result and the median time.
function timed(f; samples = SAMPLES)
    times = Float64[]
    result = nothing
    for _ in 1:samples
        GC.gc()
        t = @elapsed result = f()
        push!(times, t)
    end
    sort!(times)
    return result, times[(length(times) + 1) ÷ 2]
end

const _RESDEF = r"^\\resdef\{([^}]*)\}\{(.*)\}\s*$"

# Merges key => value pairs into results/numbers.tex, as \resdef{key}{value} lines.
function record_numbers(pairs)
    path = joinpath(RESULTS, "numbers.tex")
    numbers = Dict{String, String}()
    if isfile(path)
        for line in eachline(path)
            m = match(_RESDEF, line)
            m === nothing || (numbers[m.captures[1]] = m.captures[2])
        end
    end
    for (k, v) in pairs
        numbers[string(k)] = string(v)
    end
    open(path, "w") do io
        println(io, "% Generated by the experiments in research/ECC2027; do not edit.")
        for k in sort!(collect(keys(numbers)))
            println(io, "\\resdef{", k, "}{", numbers[k], "}")
        end
    end
    return path
end

# Thousands separated by thin spaces, from five digits on.
function group(n::Integer)
    s = string(abs(n))
    length(s) <= 4 && return string(n)
    parts = String[]
    while length(s) > 3
        pushfirst!(parts, s[(end - 2):end])
        s = s[1:(end - 3)]
    end
    pushfirst!(parts, s)
    return (n < 0 ? "-" : "") * join(parts, "\\,")
end

_cell(x::Integer) = group(x)
_cell(x) = string(x)

# Booktabs tabular in results/<name>. Integers get thousands separators; other cells are written
# as given, so they may contain LaTeX.
function write_table(name, header, rows; align = "l" * "c"^(length(header) - 1))
    path = joinpath(RESULTS, name)
    open(path, "w") do io
        println(io, "% Generated by the experiments in research/ECC2027; do not edit.")
        println(io, "\\begin{tabular}{@{}", align, "@{}}")
        println(io, "\\toprule")
        println(io, join(header, " & "), " \\\\")
        println(io, "\\midrule")
        for row in rows
            println(io, join(map(_cell, row), " & "), " \\\\")
        end
        println(io, "\\bottomrule")
        return println(io, "\\end{tabular}")
    end
    return path
end

# Date, Dionysos commit, Julia version and machine of the run. The commit is that of the loaded
# Dionysos checkout: the enclosing repository, or the clone made by environment/postInstall.
function write_environment()
    entry = Base.find_package("Dionysos")
    repo = entry === nothing ? (@__DIR__) : dirname(dirname(entry))
    commit = try
        readchomp(`git -C $repo rev-parse HEAD`)
    catch
        "unknown (not a git checkout)"
    end
    dirty = try
        isempty(readchomp(`git -C $repo status --porcelain -- src problems`)) ? "" :
        " (with uncommitted changes in src/ or problems/)"
    catch
        ""
    end
    open(joinpath(RESULTS, "environment.txt"), "w") do io
        println(io, "date: ", Dates.now())
        println(io, "Dionysos commit: ", commit, dirty)
        println(io, "SAMPLES = ", SAMPLES)
        return InteractiveUtils.versioninfo(io)
    end
    cpu = replace(Sys.cpu_info()[1].model, r"\((R|TM)\)" => "", r"\s+" => " ")
    record_numbers([
        "env.julia" => VERSION,
        "env.cpu" => strip(cpu),
        "env.samples" => SAMPLES,
    ])
    return
end

# θ, the first state coordinate, periodic on [−π, π).
function set_periodic!(optimizer)
    for (key, value) in (
        "use_periodic_mapping" => true,
        "periodic_dims" => StaticArrays.SVector(1),
        "periodic_periods" => StaticArrays.SVector(2π),
        "periodic_start" => StaticArrays.SVector(-π),
    )
        MathOptInterface.set(optimizer, MathOptInterface.RawOptimizerAttribute(key), value)
    end
    return
end

# Cells, transitions, and mean number of successors per admissible (cell, input) pair.
function abstraction_size(optimizer)
    SY = Dionysos.Symbolic
    abstract_system = MathOptInterface.get(
        optimizer,
        MathOptInterface.RawOptimizerAttribute("abstract_system"),
    )
    autom = SY.get_automaton(abstract_system)
    enabled = falses(SY.get_n_state(autom), SY.get_n_input(autom))
    ntrans = 0
    for (_, source, symbol) in SY.enum_transitions(autom)
        ntrans += 1
        enabled[source, symbol] = true
    end
    return SY.get_n_state(autom), ntrans, ntrans / max(count(enabled), 1)
end

# Angles made continuous across ±π, for plotting.
function unwrap(θ)
    out = copy(θ)
    for k in 2:length(out)
        out[k] = out[k - 1] + rem2pi(θ[k] - θ[k - 1], RoundNearest)
    end
    return out
end

# `digits` significant digits, or a whole number once the integer part has that many (1003, not
# 1000.0).
function fmt(x; digits = 3)
    r = round(x; sigdigits = digits)
    return abs(r) >= 10.0^(digits - 1) ? string(round(Int, x)) : string(r)
end
