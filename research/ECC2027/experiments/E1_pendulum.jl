# E1: pendulum swing-up with a torque limit Γ_max < m g l, baseline (B) against proposed
# approach (P).
#
# (B): full model, state (θ, θ̇), torque |Γ| ≤ Γ_max held over each step.
# (P): reduced model θ̇ = u, the command u held over each step under the impulse budget
#      |u − v| ≤ I_max = Γ_max τ (α = m l² = 1). As κ does not depend on θ, κ = κ̂ ∘ R and the
#      synthesis is complete and optimal (Remark 1 of the paper).
#
# Writes params_e1.md, table_e1.tex, fig_e1.{pdf,png}, e1_{B,P}.gif and the numbers e1.*.

module E1Pendulum

include(joinpath(@__DIR__, "..", "common.jl"))

