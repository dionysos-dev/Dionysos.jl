import MathOptInterface as MOI
import Plots
import StaticArrays: SVector
const DI = Dionysos
const PR = DI.Problem
const MP = DI.Mapping
const SY = DI.Symbolic
const AB = DI.Optim.Abstraction
const UGA = AB.UniformGridAbstraction
const OPDS = DI.Optim.DiscreteSystems

const PROBLEMS = joinpath(dirname(dirname(pathof(Dionysos))), "problems", "Pendulum")
include(joinpath(PROBLEMS, "simple_pendulum.jl"))
include(joinpath(PROBLEMS, "velocity_pendulum.jl"))
import .SimplePendulum
