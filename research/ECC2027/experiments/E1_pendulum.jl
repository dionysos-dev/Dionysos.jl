# Parameters, in SI units. The input of SimplePendulum is Γ / (m l²), which is the torque Γ for
# m = 1 kg and l = 1 m, so α = m l² = 1 and the impulse of a step from v to u is u − v.

# Physics, shared by both models
const PARAMS = SimplePendulum.Params()       # m = 1 kg, l = 1 m, g = 9.81 m/s², no friction
const G_L = PARAMS.g / PARAMS.l              # torque m g l = g needed to hold θ = 90° (N m)
const Γ_MAX = 7.0                            # torque limit of (B) (N m), Γ_max < m g l
const τ = 0.1                                # sampling period of both abstractions (s)
const I_MAX = Γ_MAX * τ                      # impulse budget of (P) (N m s)

# Task, shared by both models
const THETA_0 = 0.0                          # start: at rest at the bottom
const TARGET_HALFWIDTH = 15π / 180           # target: |θ − π| ≤ 15°, at rest

# (P) reduced model
const N_CELLS = 125                          # odd, so that θ = 0 is a cell center
const LEVELS = 10                            # speed levels on each side of 0
const DISC = VP.discretization(; τ = τ, n = N_CELLS, levels = LEVELS)
const U_BAR = DISC.u_max                     # speed limit, shared with (B)
const SLEW = floor(I_MAX / DISC.δu + 1e-9) * DISC.δu   # the budget on the command grid

# (B) full model
const H_T = SVector(3π / 180, 0.05)          # grid: 3° × 0.05 rad/s
const DTORQUE = 0.3                          # torque step of the input grid (N m)
const V_ARRIVAL = DISC.δu                    # both approaches are at rest when |θ̇| ≤ δu

function write_parameters()
    open(joinpath(RESULTS, "params_e1.md"), "w") do io
        println(io, "# E1 parameters (generated by experiments/E1_pendulum.jl)\n")
        println(io, "SI units, m = 1 kg and l = 1 m; angle θ from the bottom.\n")
        println(io, "| | value |\n|---|---|")
        for (k, v) in (
            "m g l (torque to hold θ = 90°)" => "$G_L N m",
            "torque limit Γ_max of (B)" => "$Γ_MAX N m",
            "impulse budget I_max = Γ_max τ of (P)" => "$(fmt(I_MAX)) N m s",
            "sampling period τ" => "$τ s (step commands)",
            "speed limit (both approaches)" => "$(fmt(U_BAR)) rad/s",
            "start" => "θ = 0, at rest",
            "target" => "\\|θ − π\\| ≤ 15°, at rest",
            "at rest (both approaches)" => "\\|dθ/dt\\| ≤ δu = $(fmt(V_ARRIVAL)) rad/s",
            "(P) angle cells" => "$N_CELLS (h_a = $(fmt(DISC.h)) rad)",
            "(P) command step δu = h_a/τ" => "$(fmt(DISC.δu)) rad/s",
            "(P) commands" => "$(2LEVELS + 1), from −$LEVELS δu to $LEVELS δu",
            "(P) budget on the grid" => "\\|u − v\\| ≤ $(round(Int, SLEW / DISC.δu)) δu",
            "(B) grid" => "3° × $(H_T[2]) rad/s",
            "(B) torque step" => "$DTORQUE N m",
        )
            println(io, "| ", k, " | ", v, " |")
        end
    end
    return
end

# (B): the full model
function solve_torque()
    _X_ = LazySets.Hyperrectangle(; low = SVector(-π, -U_BAR), high = SVector(π, U_BAR))
    _U_ = LazySets.Hyperrectangle(; low = SVector(-Γ_MAX), high = SVector(Γ_MAX))
    sys = SimplePendulum.system(; params = PARAMS, _X_ = _X_, _U_ = _U_)
    # The same start as (P): a quarter cell around the bottom, at rest.
    _I_ = LazySets.Hyperrectangle(;
        low = SVector(THETA_0 - DISC.h / 4, -0.01),
        high = SVector(THETA_0 + DISC.h / 4, 0.01),
    )
    _T_ = LazySets.Hyperrectangle(;
        low = SVector(π - TARGET_HALFWIDTH, -V_ARRIVAL),
        high = SVector(π + TARGET_HALFWIDTH, V_ARRIVAL),
    )
    problem = PR.OptimalControlProblem(sys, _I_, _T_, nothing, (x, u) -> 1.0, PR.Infinity())
    optimizer = MOI.instantiate(UGA.Optimizer)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("concrete_problem"), problem)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("h"), H_T)
    MOI.set(
        optimizer,
        MOI.RawOptimizerAttribute("input_grid"),
        MP.GridFree(SVector(0.0), SVector(DTORQUE)),
    )
    MOI.set(
        optimizer,
        MOI.RawOptimizerAttribute("jacobian_bound"),
        SimplePendulum.jacobian_bound(PARAMS),
    )
    MOI.set(optimizer, MOI.RawOptimizerAttribute("time_step"), τ)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("approx_mode"), UGA.GROWTH)
    set_periodic!(optimizer)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("early_stop"), true)
    MOI.set(
        optimizer,
        MOI.RawOptimizerAttribute("automaton_constructor"),
        (n, m) -> SY.FastIndexedAutomatonList(n, m),
    )
    MOI.set(optimizer, MOI.RawOptimizerAttribute("print_level"), 0)
    MOI.optimize!(optimizer)
    return optimizer
end

# (P): the reduced model. The budget starts and ends at rest.
function impulse_budget()
    return OPDS.BoundedInputVariation(
        (a, b) -> abs(a[1] - b[1]),
        SLEW + 1e-9;
        target_input = SVector(0.0),
        initial_input = SVector(0.0),
    )
end

function solve_reduced()
    sys = VP.system(DISC)
    problem = VP.swing_up_problem(
        sys;
        θ0 = THETA_0,
        target_halfwidth = TARGET_HALFWIDTH,
        h = DISC.h,
    )
    optimizer = MOI.instantiate(UGA.Optimizer)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("concrete_problem"), problem)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("state_grid"), DISC.state_grid)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("input_grid"), DISC.input_grid)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("time_step"), τ)
    # τ δu = h: a cell center moves onto a cell center, so this is exact.
    MOI.set(optimizer, MOI.RawOptimizerAttribute("approx_mode"), UGA.CENTER_SIMULATION)
    set_periodic!(optimizer)
    MOI.set(optimizer, MOI.RawOptimizerAttribute("intersample_checked"), true)
    MOI.set(
        optimizer,
        MOI.RawOptimizerAttribute("bounded_input_variation"),
        impulse_budget(),
    )
    MOI.set(optimizer, MOI.RawOptimizerAttribute("print_level"), 0)
    MOI.optimize!(optimizer)
    return optimizer
end

# The target `[π − 15°, π + 15°]` is not periodic, so an arrival near −π is wrapped first.
function at_top(x, prob)
    θ = π + rem2pi(x[1] - π, RoundNearest)
    return SVector(θ, x[2:end]...) ∈ prob.target_set
end

# (B) on the full model, stopped on entering its concrete target.
function replay_torque(optimizer; nstep = 400)
    ctrl = MOI.get(optimizer, MOI.RawOptimizerAttribute("concrete_controller"))
    sys = MOI.get(optimizer, MOI.RawOptimizerAttribute("discrete_time_system"))
    prob = MOI.get(optimizer, MOI.RawOptimizerAttribute("concrete_problem"))
    stopping = x -> at_top(x, prob)
    traj = DI.System.get_closed_loop_trajectory(
        sys,
        ctrl,
        SVector(THETA_0, 0.0),
        nstep;
        stopping,
    )
    return traj, at_top(DI.System.states(traj)[end], prob)
end

# (P) on the step dynamics θ ↦ θ + τ u. The controller stops where the stop command is
# admissible and crosses the target otherwise, so `reached` also requires the last command to
# allow the stop.
function replay_reduced(optimizer; nstep = 400)
    ctrl = MOI.get(optimizer, MOI.RawOptimizerAttribute("concrete_controller"))
    prob = MOI.get(optimizer, MOI.RawOptimizerAttribute("concrete_problem"))
    step(x, u) = SVector(x[1] + τ * u[1])
    meas(x) = SVector(rem2pi(x[1], RoundNearest))
    traj = DI.System.get_closed_loop_trajectory(
        nothing,
        ctrl,
        SVector(THETA_0),
        nstep;
        meas,
        f_map_override = step,
    )
    us = DI.System.inputs(traj)
    can_stop = !isempty(us) && abs(us[end][1]) <= SLEW + 1e-9
    return traj, at_top(DI.System.states(traj)[end], prob) && can_stop
end

# Fewest commands from the start to the target, by breadth-first search on the states (p, v) of
# the abstraction Ŝ, independent of the synthesis: the optimal cost of (P) with unit stage cost.
function fewest_steps(optimizer, constraint)
    abs_sys = MOI.get(optimizer, MOI.RawOptimizerAttribute("abstract_system"))
    prob = MOI.get(optimizer, MOI.RawOptimizerAttribute("abstract_problem"))
    κ = UGA.lift_bounded_input_variation(abs_sys, constraint)
    succ = Dict{Tuple{Int, Int}, Vector{Int}}()
    for (t, q, u) in SY.enum_transitions(SY.get_automaton(abs_sys))
        push!(get!(succ, (q, u), Int[]), t)
    end
    inputs = collect(SY.enum_inputs(abs_sys))
    targets = Set(prob.target_set)
    # A target cell entered too fast to stop is crossed like any other cell.
    arrived((q, v)) = q in targets && κ.compatible[v, κ.target_input]
    frontier = [(SY.get_abstract_state(abs_sys, SVector(THETA_0)), κ.initial_input)]
    seen = Set(frontier)
    for steps in 0:(length(inputs) * SY.get_n_state(SY.get_automaton(abs_sys)))
        any(arrived, frontier) && return steps
        next = Tuple{Int, Int}[]
        for (q, v) in frontier
            for u in inputs
                κ.compatible[v, u] || continue
                for t in get(succ, (q, u), Int[])
                    (t, u) in seen || (push!(seen, (t, u)); push!(next, (t, u)))
                end
            end
        end
        isempty(next) && return nothing
        frontier = next
    end
    return nothing
end

# Angle and hold torque Γ_hold = g sin θ between samples, under the step commands `us`.
function hold_profile(θs, us; samples = 101)
    ts, θ, torque = Float64[], Float64[], Float64[]
    t0 = 0.0
    for (k, u) in enumerate(us)
        for t in range(0, τ; length = samples)
            th = θs[k] + u * t
            push!(ts, t0 + t)
            push!(θ, th)
            push!(torque, G_L * sin(th))
        end
        t0 += τ
    end
    return ts, θ, torque
end

# Runs
write_parameters()

solvers = (; B = solve_torque, P = solve_reduced)
results = Dict{Symbol, Any}()
for (name, solve) in pairs(solvers)
    solve() # compile, so the timed round does not pay for it
    optimizer, t = timed(solve)
    success = MOI.get(optimizer, MOI.RawOptimizerAttribute("success"))
    cells, ntrans, nsucc = abstraction_size(optimizer)
    results[name] = (; success, cells, ntrans, nsucc, t, optimizer)
    println((name, (; success, cells, ntrans, nsucc, t)))
end

numbers = Dict{String, Any}(
    "e1.gl" => G_L,
    "e1.Gmax" => Γ_MAX,
    "e1.Imax" => fmt(I_MAX),
    "e1.tau" => τ,
    "e1.umax" => fmt(U_BAR),
    "e1.P.ncells" => N_CELLS,
    "e1.P.hdeg" => fmt(rad2deg(DISC.h)),
    "e1.P.du" => fmt(DISC.δu),
    "e1.P.levels" => LEVELS,
    "e1.P.nsigma" => 2LEVELS + 1,
    "e1.B.hdeg" => fmt(rad2deg(H_T[1])),
    "e1.B.hv" => H_T[2],
    "e1.B.dtorque" => DTORQUE,
    "e1.budget.steps" => round(Int, SLEW / DISC.δu),
)
for (name, r) in results
    numbers["e1.$name.cells"] = r.cells
    numbers["e1.$name.trans"] = r.ntrans
    numbers["e1.$name.succ"] = fmt(r.nsucc; digits = 2)
    numbers["e1.$name.time"] = fmt(r.t)
end
numbers["e1.ratio.cells"] = round(Int, results[:B].cells / results[:P].cells)
numbers["e1.ratio.trans"] = round(Int, results[:B].ntrans / results[:P].ntrans)

traj = Dict{Symbol, Any}()
if results[:B].success
    tr, reached = replay_torque(results[:B].optimizer)
    reached || error("(B) did not reach the target on the full model")
    uB = [u[1] for u in DI.System.inputs(tr)]
    traj[:B] = (; tr, reached)
    numbers["e1.B.steps"] = length(uB)
    numbers["e1.B.maxtorque"] = fmt(maximum(abs, uB))
end
if results[:P].success
    tr, reached = replay_reduced(results[:P].optimizer)
    θs = [x[1] for x in DI.System.states(tr)]
    us = [u[1] for u in DI.System.inputs(tr)]
    impulses = us .- vcat(0.0, us[1:(end - 1)])      # α = 1: the impulse is the change of command
    profile = hold_profile(θs, us)
    traj[:P] = (; tr, reached, θs, us, impulses, profile)
    numbers["e1.P.steps"] = length(us)
    numbers["e1.P.maximpulse"] = fmt(maximum(abs, vcat(impulses, us[end])))  # with the stop
    numbers["e1.P.maxhold"] = fmt(maximum(abs, profile[3]))
end
# (P) is sound: its replay must reach the target within the budget.
traj[:P].reached || error("(P) did not reach the target on the step dynamics")
parse(Float64, numbers["e1.P.maximpulse"]) <= I_MAX + 1e-9 ||
    error("(P) exceeds the impulse budget")
# Optimality, stated in Section VI-A.
numbers["e1.P.fewest"] =
    something(fewest_steps(results[:P].optimizer, impulse_budget()), "none")
numbers["e1.P.fewest"] == numbers["e1.P.steps"] ||
    @warn "(P) replay takes $(numbers["e1.P.steps"]) steps, but the fewest is $(numbers["e1.P.fewest"]): update the optimality claim of Section VI-A"
record_numbers(numbers)
for name in keys(solvers)
    haskey(traj, name) || (println("($name) unsolved"); continue)
    println(
        "($name) ",
        numbers["e1.$name.steps"],
        " steps",
        name === :B ? ", peak torque $(numbers["e1.B.maxtorque"]) (Γ_max = $Γ_MAX)" :
        ", peak impulse $(numbers["e1.P.maximpulse"]) (I_max = $(fmt(I_MAX))), peak hold torque $(numbers["e1.P.maxhold"])",
    )
end

# Columns as in Table I: (B) has no impulses, and "--" marks an unsolved task.
function table_row(name)
    r = results[name]
    solved = haskey(traj, name)
    impulse = name === :B ? "n/a" : solved ? numbers["e1.P.maximpulse"] : "--"
    force =
        !solved ? "--" :
        bold_above(numbers[name === :B ? "e1.B.maxtorque" : "e1.P.maxhold"], Γ_MAX)
    return [
        "($name)",
        r.cells,
        r.ntrans,
        numbers["e1.$name.succ"],
        numbers["e1.$name.time"],
        solved ? numbers["e1.$name.steps"] : "--",
        impulse,
        force,
    ]
end
