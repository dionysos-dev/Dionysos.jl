# Figures
# Cart and pole, θ from the upright.
function cart_plot!(; l = PARAMS.l, w = 0.4, h = 0.2)
    return function (fig, s, _)
        x, θ = s[1], s[2]
        Plots.plot!(
            fig,
            [x - w / 2, x + w / 2, x + w / 2, x - w / 2, x - w / 2],
            [0, 0, h, h, 0];
            fill = (true, 0.25),
            color = :blue,
            label = "",
        )
        pivot = (x, h)
        tip = (x + l * sin(θ), h + l * cos(θ))
        Plots.plot!(
            fig,
            [pivot[1], tip[1]],
            [pivot[2], tip[2]];
            lw = 3,
            color = :black,
            label = "",
        )
        Plots.scatter!(fig, [tip[1]], [tip[2]]; ms = 6, color = :red, label = "")
        Plots.plot!(fig, [-1.0, 3.0], [0, 0]; color = :black, label = "")
        return fig
    end
end

