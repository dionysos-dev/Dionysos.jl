# =============================================================================== parameters
const PARAMS = PM.Params()          # M = 1 kg cart, m = 0.2 kg at l = 1 m, g = 9.81
const F_MAX = 20.0                  # force limit of (T) (N)
const V_MAX = 2.0                   # cart speed limit (m/s)
const τ = 0.05                      # sampling period (s)
const I_MAX = F_MAX * τ             # impulse budget of (F) (N s)
const θ_TARGET = 0.2                # target: |θ| ≤ 0.2 rad ...
const P_TARGET = 0.2                # ... and |p_θ| ≤ 0.2 kg m²/s

# (F): cells in (θ, p_θ), commands on a grid
const N_θ = 251
const H_P = 0.02
const P_MAX = 2.0
const δu = 0.25

# (T): cells in (θ, ẋ, θ̇), forces on a grid
const H_V = 0.2
const H_ω = 0.2
const ω_MAX = 10.0
const DF = 2.0

# The grids of the runs, and coarse ones that compile the code before the timed runs.
const GRIDS = (F = (nθ = N_θ, hp = H_P), T = (nθ = N_θ, hv = H_V, hω = H_ω))
const COARSE = (F = (nθ = 31, hp = 0.2), T = (nθ = 31, hv = 0.4, hω = 1.0))

# Command notches that the impulse budget allows per step, at the inertia α.
notches(α) = floor(Int, (I_MAX + 1e-9) / (α * δu))

function write_parameters()
    nΣ = 2 * round(Int, V_MAX / δu) + 1
    # (F) bounds α over each cell, which the exact budget does not.
    hθ = 2π / N_θ
    lo, hi = extrema(
        notches(PM.inertia_bound(PARAMS, (θ - hθ / 2, θ + hθ / 2))) for
        θ in (-π + hθ / 2) .+ hθ .* (0:(N_θ - 1))
    )
    per_cell = lo == hi ? "$lo in every cell" : "$lo to $hi, depending on the cell"
    open(joinpath(RESULTS, "params_e2.md"), "w") do io
        println(io, "# E2 parameters (generated by experiments/E2_cartpole.jl)\n")
        println(io, "| | value |\n|---|---|")
        for (k, v) in (
            "cart mass M, pole mass m, length l" => "$(PARAMS.M) kg, $(PARAMS.m) kg, $(PARAMS.l) m",
            "force limit of (T)" => "$F_MAX N",
            "impulse budget of (F)" => "$I_MAX N s (= F_max τ)",
            "cart speed limit" => "$V_MAX m/s",
            "sampling period τ" => "$τ s (step commands)",
            "start" => "hanging down, at rest",
            "target" => "\\|θ\\| ≤ $θ_TARGET rad, \\|p_θ\\| ≤ $P_TARGET kg m²/s, any cart velocity",
            "(F) grid" => "$N_θ × $(round(Int, 2P_MAX / H_P)) cells in (θ, p_θ), \\|p_θ\\| ≤ $P_MAX kg m²/s",
            "(F) commands" => "$nΣ speeds, notch $δu m/s",
            "(F) notches per step" => "$per_cell, with α bounded over the cell (the exact budget allows $(notches(PARAMS.M)) at θ = 0)",
            "(T) grid" => "$N_θ × $(round(Int, 2V_MAX / H_V)) × $(round(Int, 2ω_MAX / H_ω)) cells in (θ, ẋ, θ̇)",
            "(T) forces" => "$(2 * round(Int, F_MAX / DF) + 1) levels, step $DF N",
        )
            println(io, "| ", k, " | ", v, " |")
        end
    end
    return
end

# =================================================================================== models
# θ is periodic, with cell edges at ±π; each grid has its origin at its first cell center.

# (F). The target is the cells inside |θ| ≤ θ_TARGET, |p_θ| ≤ P_TARGET. The Jacobian bound holds
# for |p_θ| ≤ P_MAX + 0.5: in one step p_θ moves by less than 0.4 (|ṗ_θ| < 7.8).
function model_F(; nθ, hp)
    hθ = 2π / nθ
    grid = MP.GridFree(SVector(-π + hθ / 2, -P_MAX + hp / 2), SVector(hθ, hp))
    box = LazySets.Hyperrectangle(;
        low = SVector(-θ_TARGET, -P_TARGET),
        high = SVector(θ_TARGET, P_TARGET),
    )
    return (;
        system = PM.velocity_system(PARAMS; p_max = P_MAX, v_max = V_MAX),
        grid,
        input_grid = MP.GridFree(SVector(0.0), SVector(δu)),
        target = MP.CellUnion(grid, MP.get_pos_from_set(grid, box, MP.INNER)),
        start = SVector(π - hθ / 2, 0.0),
        jacobian_bound = PM.velocity_jacobian_bound(PARAMS; p_max = P_MAX + 0.5),
        constraint = PM.impulse_budget(PARAMS, I_MAX),
    )
end

# (T). The target is the same physical set, p_θ = m l² θ̇ + m l cos θ ẋ, over whole cells.
function model_T(; nθ, hv, hω)
    hθ = 2π / nθ
    grid = MP.GridFree(
        SVector(-π + hθ / 2, -V_MAX + hv / 2, -ω_MAX + hω / 2),
        SVector(hθ, hv, hω),
    )
    near_upright = LazySets.Hyperrectangle(;
        low = SVector(-2θ_TARGET, -V_MAX, -ω_MAX),
        high = SVector(2θ_TARGET, V_MAX, ω_MAX),
    )
    target = MP.cells_where(grid, near_upright, MP.INNER) do pos
        cell = MP.get_rec(grid, pos)
        return PM.in_force_target(
            PARAMS,
            PM.interval(cell, 1),
            PM.interval(cell, 2),
            PM.interval(cell, 3);
            θ_target = θ_TARGET,
            p_target = P_TARGET,
        )
    end
    return (;
        system = PM.force_system(PARAMS; v_max = V_MAX, ω_max = ω_MAX, F_max = F_MAX),
        grid,
        input_grid = MP.GridFree(SVector(0.0), SVector(DF)),
        target,
        start = SVector(π - hθ / 2, 0.0, 0.0),
        jacobian_bound = PM.force_cellwise_bound(PARAMS),
        constraint = nothing,
    )
end

# Both abstractions integrate the center and the growth bound by RK4 in 20 substeps. The target
# cells get no transitions: a run ends there.
function solve(model)
    init = LazySets.Hyperrectangle(; low = model.start .- 1e-3, high = model.start .+ 1e-3)
    problem = PR.OptimalControlProblem(
        model.system,
        init,
        model.target,
        nothing,
        (x, u) -> 1.0,
        PR.Infinity(),
    )
    optimizer = MOI.instantiate(UGA.Optimizer)
    set(key, value) = MOI.set(optimizer, MOI.RawOptimizerAttribute(key), value)
    set("concrete_problem", problem)
    set("state_grid", model.grid)
    set("input_grid", model.input_grid)
    set("time_step", τ)
    set("approx_mode", UGA.GROWTH)
    set("jacobian_bound", model.jacobian_bound)
    set("nsystem", 20)
    set("ngrowthbound", 20)
    set_periodic!(optimizer)
    set("state_filter", x -> !(x in model.target))
    model.constraint === nothing || set("bounded_input_variation", model.constraint)
    set("execution_backend", SY.ThreadedBackend())
    set("print_level", 0)
    MOI.optimize!(optimizer)
    return optimizer
end

# =================================================================================== replays
wrap(z) = Base.setindex(z, rem2pi(z[1], RoundNearest), 1)

"""
    replay_F(optimizer, model; nmax = 2000, K = 20)

Run the controller of (F) on the exact step dynamics from the start at rest, sampling each step
`K` times: the times, angle, angular velocity, cart position, the hold force
`m sin θ (g cos θ − l θ̇²)` between samples, the impulse `α(θ)(u − v)` of each step, and whether
the target was reached.
"""
function replay_F(optimizer, model; nmax = 2000, K = 20)
    ctrl = MOI.get(optimizer, MOI.RawOptimizerAttribute("concrete_controller"))
    f = PM.velocity_dynamics(PARAMS)
    out = (t = Float64[], θ = Float64[], θdot = Float64[], x = Float64[], F = Float64[])
    impulses = Float64[]
    z, mem, v, x, t = model.start, ST.initial_state(ctrl), 0.0, 0.0, 0.0
    reached = false
    h = τ / K
    for _ in 1:nmax
        if wrap(z) in model.target
            reached = true
            break
        end
        command = ST.output_control(ctrl, mem, wrap(z))
        command === nothing && break
        u = command[1]
        push!(impulses, (PARAMS.M + PARAMS.m * sin(z[1])^2) * (u - v))
        mem = ST.update_state(ctrl, mem, wrap(z))
        for j in 0:(K - 1)
            θdot = PM.angular_velocity(PARAMS, z[1], z[2], u)
            push!(out.t, t + j * h)
            push!(out.θ, z[1])
            push!(out.θdot, θdot)
            push!(out.x, x + u * j * h)
            push!(out.F, PM.cart_force(PARAMS, z[1], θdot, 0.0))
            z = ST.runge_kutta4(f, z, u, h, 1)
        end
        x += u * τ
        t += τ
        v = u
    end
    return (; out..., impulses, reached)
end

"""
    replay_T(optimizer, model; nmax = 2000, K = 20)

Run the controller of (T) on the force dynamics from the start at rest, the force held over each
step, with the same samples as `replay_F`.
"""
function replay_T(optimizer, model; nmax = 2000, K = 20)
    ctrl = MOI.get(optimizer, MOI.RawOptimizerAttribute("concrete_controller"))
    f = PM.force_dynamics(PARAMS)
    out = (t = Float64[], θ = Float64[], θdot = Float64[], x = Float64[], F = Float64[])
    y, mem, x, t = model.start, ST.initial_state(ctrl), 0.0, 0.0
    reached = false
    h = τ / K
    for _ in 1:nmax
        if wrap(y) in model.target
            reached = true
            break
        end
        command = ST.output_control(ctrl, mem, wrap(y))
        command === nothing && break
        F = command[1]
        mem = ST.update_state(ctrl, mem, wrap(y))
        for j in 0:(K - 1)
            push!(out.t, t + j * h)
            push!(out.θ, y[1])
            push!(out.θdot, y[3])
            push!(out.x, x)
            push!(out.F, F)
            ynext = ST.runge_kutta4(f, y, F, h, 1)
            x += (y[2] + ynext[2]) * h / 2
            y = ynext
        end
        t += τ
    end
    return (; out..., impulses = Float64[], reached)
end

# ==================================================================================== runs
write_parameters()

# (T) takes minutes, so it is timed once.
const RUNS = (
    T = (; model = model_T, replay = replay_T, samples = 1),
    F = (; model = model_F, replay = replay_F, samples = SAMPLES),
)
results = Dict{Symbol, Any}()
for (name, run) in pairs(RUNS)
    solve(run.model(; COARSE[name]...))
    model = run.model(; GRIDS[name]...)
    optimizer, t = timed(() -> solve(model); run.samples)
    cells, ntrans, nsucc = abstraction_size(optimizer)
    ctrl = MOI.get(optimizer, MOI.RawOptimizerAttribute("concrete_controller"))
    solved = ST.output_control(ctrl, ST.initial_state(ctrl), model.start) !== nothing
    replay = solved ? run.replay(optimizer, model) : nothing
    results[name] = (; solved, cells, ntrans, nsucc, t, replay)
    println((name, (; solved, cells, ntrans, nsucc, t)))
    optimizer = ctrl = nothing
    GC.gc()
end

numbers = Dict{String, Any}(
    "e2.Fmax" => F_MAX,
    "e2.Imax" => I_MAX,
    "e2.vmax" => V_MAX,
    "e2.tau" => τ,
    "e2.du" => δu,
    "e2.F.ntheta" => N_θ,
    "e2.F.np" => round(Int, 2P_MAX / H_P),
    "e2.F.nsigma" => 2 * round(Int, V_MAX / δu) + 1,
)
for (name, r) in results
    numbers["e2.$name.cells"] = r.cells
    numbers["e2.$name.stored"] = r.ntrans
    numbers["e2.$name.succ"] = fmt(r.nsucc; digits = 2)
    numbers["e2.$name.time"] = fmt(r.t)
    numbers["e2.$name.solved"] = r.solved ? "yes" : "no"
    r.solved || continue
    rp = r.replay
    rp.reached || error("($name) did not reach the target on the exact dynamics")
    numbers["e2.$name.steps"] = length(rp.t) ÷ 20 # the replays sample each step 20 times
    if name === :F
        peak = maximum(abs, rp.impulses)
        peak <= I_MAX + 1e-9 || error("(F) exceeds the impulse budget: $peak")
        numbers["e2.F.maximpulse"] = fmt(peak)
        numbers["e2.F.maxhold"] = fmt(maximum(abs, rp.F))
    else
        maximum(abs, rp.F) <= F_MAX + 1e-9 || error("(T) exceeds the force limit")
        numbers["e2.T.maxforce"] = fmt(maximum(abs, rp.F))
    end
end
numbers["e2.ratio.cells"] = round(Int, results[:T].cells / results[:F].cells)
numbers["e2.ratio.stored"] = fmt(results[:T].ntrans / results[:F].ntrans; digits = 3)
