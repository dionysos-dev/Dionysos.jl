# E2, cart-pole swing-up: the classical force model (T) against the velocity model (F).
#
# A frictionless cart-pole (point mass at the tip, θ from the upright) starts at rest, hanging
# down, and must reach a neighborhood of the upright, |θ| ≤ 0.2 rad and |p_θ| ≤ 0.2, where a
# local stabilizer takes over. The cart force of (T) is limited to F_MAX; the cart velocity of (F)
# is commanded on a grid, in steps, under the impulse budget |α(θ)(u − v)| ≤ I_MAX = F_MAX τ, the
# impulse a force-limited actuator delivers over one step. The cart position enters neither the
# dynamics of the pole nor the task, so both models leave it out.
#
#   (T)  force model, state (θ, ẋ, θ̇), the force held over each step.
#   (F)  velocity model, state (θ, p_θ), one successor set per (cell, command) from a growth
#        bound; the impulse budget decides which command may follow which, in Algorithm 1.
#
# Every controller is replayed on the exact dynamics; (F) reports the impulse of each step and
# the hold force between samples, which the budget does not bound.
#
# Writes results/params_e2.md, results/table_e2.tex, results/fig_e2.{pdf,png},
# results/e2_{T,F}.gif, and the numbers e2.*.

module E2CartPole

include(joinpath(@__DIR__, "..", "common.jl"))
include(joinpath(@__DIR__, "cartpole_abstraction.jl"))

import Dionysos
import Plots
import StaticArrays: SVector
const CA = CartPoleAbstraction
const VC = CA.VC
const ST = Dionysos.System

# =============================================================================== parameters
const PARAMS = VC.Params()          # M = 1 kg cart, m = 0.2 kg at l = 1 m, g = 9.81
const F_MAX = 20.0                  # force limit of (T) (N)
const V_MAX = 2.0                   # cart speed limit (m/s)
const τ = 0.05                      # sampling period (s)
const I_MAX = F_MAX * τ             # impulse budget of (F) (N s)
const θ_TARGET = 0.2                # target: |θ| ≤ 0.2 rad ...
const P_TARGET = 0.2                # ... and |p_θ| ≤ 0.2 kg m²/s

# (F): cells in (θ, p_θ), commands on a grid
const N_θ = 251
const H_P = 0.02
const P_MAX = 2.0
const δu = 0.25
const LEVELS = round(Int, V_MAX / δu)
const Σ = collect(δu .* ((-LEVELS):LEVELS))

# (T): cells in (θ, ẋ, θ̇), forces on a grid
const T_GRID = (nθ = 251, hv = 0.2, hω = 0.2, ω_max = 10.0)
const DF = 2.0
const FORCES = collect((-F_MAX):DF:F_MAX)

function write_parameters()
    open(joinpath(RESULTS, "params_e2.md"), "w") do io
        println(io, "# E2 parameters (generated by experiments/E2_cartpole.jl)\n")
        println(io, "| | value |\n|---|---|")
        for (k, v) in (
            "cart mass M, pole mass m, length l" => "$(PARAMS.M) kg, $(PARAMS.m) kg, $(PARAMS.l) m",
            "force limit of (T)" => "$F_MAX N",
            "impulse budget of (F)" => "$I_MAX N s (= F_max τ)",
            "cart speed limit" => "$V_MAX m/s",
            "sampling period τ" => "$τ s (step commands)",
            "start" => "hanging down, at rest",
            "target" => "|θ| ≤ $θ_TARGET rad, |p_θ| ≤ $P_TARGET kg m²/s, any cart velocity",
            "(F) grid" => "$N_θ × $(round(Int, 2P_MAX / H_P)) cells in (θ, p_θ), |p_θ| ≤ $P_MAX kg m²/s",
            "(F) commands" => "$(length(Σ)) speeds, notch $δu m/s",
            "(F) notches per step" => "$(floor(Int, I_MAX / (PARAMS.M * δu) + 1e-9)) at θ = 0, $(floor(Int, I_MAX / ((PARAMS.M + PARAMS.m) * δu) + 1e-9)) at θ = ±90°",
            "(T) grid" => "$(T_GRID.nθ) × $(round(Int, 2V_MAX / T_GRID.hv)) × $(round(Int, 2T_GRID.ω_max / T_GRID.hω)) cells in (θ, ẋ, θ̇)",
            "(T) forces" => "$(length(FORCES)) levels, step $DF N",
        )
            println(io, "| ", k, " | ", v, " |")
        end
    end
    return
end

# ================================================================================ targets
function target_F(G)
    t = falses(CA.ncells(G))
    for c in 1:CA.ncells(G)
        Θ, Pp = CA.bounds(G, c)
        t[c] =
            -θ_TARGET <= Θ[1] && Θ[2] <= θ_TARGET && -P_TARGET <= Pp[1] && Pp[2] <= P_TARGET
    end
    return t
end

# The same physical set for (T): p_θ = m l² θ̇ + m l cos θ ẋ over whole cells.
function target_T(G)
    P = PARAMS
    t = falses(CA.ncells(G))
    r = CA.halfwidth(G)
    for c in 1:CA.ncells(G)
        y = CA.center(G, c)
        Θ = (y[1] - r[1], y[1] + r[1])
        (-θ_TARGET <= Θ[1] && Θ[2] <= θ_TARGET) || continue
        p = VC.iadd(
            VC.iscale(P.m * P.l^2, (y[3] - r[3], y[3] + r[3])),
            VC.iscale(P.m * P.l, VC.imul(VC.icos(Θ), (y[2] - r[2], y[2] + r[2]))),
        )
        t[c] = -P_TARGET <= p[1] && p[2] <= P_TARGET
    end
    return t
end

# ==================================================================================== runs
function run_F()
    G = CA.Grid(N_θ, H_P, P_MAX)
    target = target_F(G)
    t = @elapsed (A, (value, choice)) = (() -> begin
        A = CA.build(PARAMS, G, Σ, τ, target)
        compatible = CA.impulse_budget(PARAMS, G, Σ, I_MAX)
        (A, CA.synthesize(A, target; compatible))
    end)()
    z0 = SVector(π - G.hθ / 2, 0.0)
    start = CA.locate(G, z0) + CA.ncells(G) * (findfirst(==(0.0), Σ) - 1)
    solved = value[start] < Inf
    replay = solved ? CA.replay(A, choice, PARAMS, τ, z0, target) : nothing
    return (; A, G, value, solved, replay, t, cells = CA.ncells(G))
end

function run_T()
    G = CA.Grid3(T_GRID.nθ, T_GRID.hv, V_MAX, T_GRID.hω, T_GRID.ω_max)
    target = target_T(G)
    t = @elapsed (A, (value, choice)) = (() -> begin
        A = CA.build_T(PARAMS, G, FORCES, τ, target)
        (A, CA.synthesize(A, target))
    end)()
    y0 = SVector(π - G.hθ / 2, 0.0, 0.0)
    solved = value[CA.locate(G, y0)] < Inf
    replay = solved ? CA.replay_T(A, choice, PARAMS, τ, y0, target) : nothing
    return (; A, G, value, solved, replay, t, cells = CA.ncells(G))
end

write_parameters()
results = Dict{Symbol, Any}()
for (name, run) in ((:F, run_F), (:T, run_T))
    results[name] = run()
    r = results[name]
    println((
        name,
        (; r.solved, r.cells, pairs = length(r.A.pairs), stored = r.A.stored, r.t),
    ))
    GC.gc()
end

numbers = Dict{String, Any}(
    "e2.Fmax" => F_MAX,
    "e2.Imax" => I_MAX,
    "e2.vmax" => V_MAX,
    "e2.tau" => τ,
    "e2.du" => δu,
    "e2.F.ntheta" => N_θ,
    "e2.F.np" => round(Int, 2P_MAX / H_P),
    "e2.F.nsigma" => length(Σ),
)
for (name, r) in results
    numbers["e2.$name.cells"] = r.cells
    numbers["e2.$name.stored"] = r.A.stored
    numbers["e2.$name.succ"] = fmt(r.A.stored / max(length(r.A.pairs), 1); digits = 2)
    numbers["e2.$name.time"] = fmt(r.t)
    numbers["e2.$name.solved"] = r.solved ? "yes" : "no"
    r.solved || continue
    rp = r.replay
    rp.reached || error("($name) did not reach the target on the exact dynamics")
    numbers["e2.$name.steps"] = length(rp.t) ÷ 20 # the replays sample each step 20 times
    numbers["e2.$name.maxforce"] = fmt(maximum(abs, rp.F))
    if name === :F
        peak = maximum(abs, rp.impulses)
        peak <= I_MAX + 1e-9 || error("(F) exceeds the impulse budget: $peak")
        numbers["e2.F.maximpulse"] = fmt(peak)
        numbers["e2.F.maxhold"] = numbers["e2.F.maxforce"]
    else
        maximum(abs, rp.F) <= F_MAX + 1e-9 || error("(T) exceeds the force limit")
    end
end
numbers["e2.ratio.cells"] = round(Int, results[:T].cells / results[:F].cells)
numbers["e2.ratio.stored"] = fmt(results[:T].A.stored / results[:F].A.stored; digits = 3)
record_numbers(numbers)

